/** Wired mic shortcuts. */
const dyn = (maker: string, model: string, summary: string, tags = '') => mic(maker, model, summary, { tags: `dynamic${tags ? ', ' + tags : ''}` })
const cond = (maker: string, model: string, summary: string, tags = '') => mic(maker, model, summary, { tags: `condenser, phantom${tags ? ', ' + tags : ''}` })
const lav = (maker: string, model: string, summary: string) => mic(maker, model, summary, { mount: 'portable', kg: 0.05, tags: 'lavalier, wireless' })
const gooseneck = (maker: string, model: string, summary: string) => mic(maker, model, summary, { tags: 'gooseneck, condenser, phantom' })
/** Wireless receivers. */
const rx = (maker: string, model: string, summary: string, io: string, spec: Parameters<typeof P>[5] = {}) => P(maker, model, 'wirelessReceiver', summary, io, { ru: 1, w: 20, ...spec })
/** Body-pack / handheld transmitters: battery powered, no ports to wire. */
const tx = (maker: string, model: string, summary: string, io = 'nopower') => P(maker, model, 'microphone', summary, io, { mount: 'portable', kg: 0.2, w: 0, tags: 'wireless, transmitter' })
const ic = (maker: string, model: string, summary: string, io: string, spec: Parameters<typeof P>[5] = {}) => P(maker, model, 'intercom', summary, io, { ru: 1, ...spec })
const vc = (maker: string, model: string, summary: string, io: string, spec: Parameters<typeof P>[5] = {}) => P(maker, model, 'conferencing', summary, io, { mount: 'shelf', ...spec })

